# tab:gate -- the competence gate over all sixteen pairs
# ---------------------------------------------------------------------------
def table_gate(out: Path) -> dict:
    src = TIST / "e4" / "competence.json"
    comp = json.loads(src.read_text(encoding="utf-8"))
    _prov("tab:gate", "accuracy, binomial p, admit or exclude verdict", src)

    order = OPEN_ORDER + ["mistral-medium", "qwen3-next-80b-a3b",
                          "amazon-nova-2-lite", "gemini-2.5-flash"]
    body = [r"\begin{tabular}{llrrrl}", r"\toprule",
            r"Model & Access & \multicolumn{2}{c}{Accuracy} & Floor & Verdict \\",
            r"\cmidrule(lr){3-4}",
            r" & & Hindi & Bengali & & \\", r"\midrule"]
    for m in order:
        cells = {lg: comp.get(f"{m}|{lg}") for lg in ("hi", "bn")}
        if not any(cells.values()):
            continue
        access = "open" if m in OPEN_ORDER else "API"

        def _c(lg: str) -> str:
            c = cells[lg]
            if not c:
                return "--"
            s = f"{c['accuracy']:.3f}"
            return s if c["competent"] else f"\\textbf{{{s}}}"

        admitted = [LANG[lg] for lg in ("hi", "bn") if cells[lg] and cells[lg]["competent"]]
        verdict = ", ".join(admitted) if admitted else "excluded"
        body.append(f"{_disp(m)} & {access} & {_c('hi')} & {_c('bn')} & 0.50 & "
                    f"{verdict} \\\\")
    body += [r"\bottomrule", r"\end{tabular}"]

    n_ok = sum(1 for v in comp.values() if v["competent"])
    n_below = sum(1 for v in comp.values() if v["accuracy"] < 1 / 3)
    cap = (f"Competence gate over {len(comp)} model and language pairs; {n_ok} admitted. "
           f"Bold marks an excluded pair, and chance is 0.333.")
    (out / "tab_gate.tex").write_text(_float("tab:gate", cap, "\n".join(body)),
                                      encoding="utf-8")
    return {"n_pairs": len(comp), "n_ok": n_ok, "n_excluded": len(comp) - n_ok,
            "n_below_chance": n_below}


