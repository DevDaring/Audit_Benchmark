# fig:multilingual -- the same item in three languages
# ---------------------------------------------------------------------------
def figure_multilingual(out: Path, figdir: Path) -> None:
    """Rendered to PDF rather than typeset.

    pdflatex cannot set Devanagari or Bengali without switching engine to XeLaTeX, and
    acmart submissions are expected to build under pdflatex. Drawing the text into a
    vector PDF with a font that covers both scripts keeps the build unchanged.
    """
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib import font_manager

    en = pd.read_parquet(DATASET / "pentad_dataset_clean.parquet")
    rows = []
    q = en[(en.seed_id == RUNNING_SEED) & (en.slot == "a")]
    if q.empty:
        log.warning("running seed absent in English; skipping fig:multilingual")
        return
    rows.append(("English", q.prompt_text.iloc[0]))
    for lang, label in (("hi", "Hindi"), ("bn", "Bengali")):
        p = DATASET / f"pentad_{lang}.parquet"
        if not p.exists():
            continue
        d = pd.read_parquet(p)
        s = d[(d.seed_id == RUNNING_SEED) & (d.slot == "a")]
        if not s.empty:
            rows.append((label, s.prompt_text.iloc[0]))
            _prov("fig:multilingual", f"{label} translation of the running seed", p)
    _prov("fig:multilingual", "English text of the running seed",
          DATASET / "pentad_dataset_clean.parquet")

    # A font covering Devanagari and Bengali. Nirmala UI ships with Windows; the run
    # records which font was used so the figure can be reproduced elsewhere.
    chosen = None
    for cand in ("Nirmala UI", "Noto Sans Devanagari", "Mangal", "Vrinda"):
        try:
            font_manager.findfont(font_manager.FontProperties(family=cand),
                                  fallback_to_default=False)
            chosen = cand
            break
        except Exception:
            continue
    if chosen is None:
        log.warning("no Indic-capable font found; fig:multilingual would render as boxes")
        return
    log.info("rendering multilingual figure with %r", chosen)

    fig, ax = plt.subplots(figsize=(5.4, 3.4))
    ax.axis("off")
    y = 1.0
    for label, text in rows:
        keep = [l for l in text.split("\n") if not l.startswith("Answer with")]
        ax.text(0, y, label, fontsize=8, fontweight="bold", family="DejaVu Sans",
                transform=ax.transAxes, va="top")
        y -= 0.055
        for line in keep:
            ax.text(0.02, y, line, fontsize=7.5, family=chosen,
                    transform=ax.transAxes, va="top")
            y -= 0.052
        y -= 0.035
    fig.tight_layout(pad=0.2)
    figdir.mkdir(parents=True, exist_ok=True)
    fig.savefig(figdir / "fig_multilingual.pdf")
    plt.close(fig)

    cap = ("The running seed in all three audited languages. Option letters and the answer "
           "set are preserved by construction, so the gold answer is unchanged.")
    (out / "fig_multilingual.tex").write_text(
        "%% generated by TIST/make_tables.py -- do not edit by hand\n"
        "\\begin{figure}[t]\n\\centering\n"
        "\\includegraphics[width=\\linewidth]{figures/fig_multilingual.pdf}\n"
        f"\\caption{{{cap}}}\n\\label{{fig:multilingual}}\n\\end{{figure}}\n",
        encoding="utf-8")


