"""
File: TIST/make_tables.py
Purpose: Generate every LaTeX float in the TIST manuscript from the result files, so no
         number in the paper is ever typed by hand.

The rule this module enforces: a number appears in the manuscript only if this script can
produce it from a file under results/tist/ or results/. Alongside the floats it writes
number_provenance.csv, which maps every table to the file it was built from. That file is
the answer to "where did this number come from" during review.

Two conventions follow the rejection lessons:

  - Captions are one line. The explanation belongs in the running text, so a caption here
    says what the table holds and nothing else. TIST/style_check.py fails a caption over
    200 characters.
  - A figure never restates a table. The layer figure shows the depth profile, which no
    table reports; the tables report scalars, which the figure does not.

Competence filtering. Multilingual severity is reported only for model and language pairs
that pass the competence gate in results/tist/e4/competence.json. The severity file still
carries rows for gated-out pairs because it is written before the gate is applied, and
publishing those rows would report comprehension failure as bias.

Implements / builds on / cites:
  - Youden (1950). "Index for rating diagnostic tests." Cancer 3(1):32-35.
  - Holm (1979). "A simple sequentially rejective multiple test procedure."
    Scandinavian Journal of Statistics 6(2):65-70.

Usage:
  python TIST/make_tables.py
  python TIST/make_tables.py --out ../../Submission

Part of the audit codebase (MIRAGE, TIST resubmission).
"""

