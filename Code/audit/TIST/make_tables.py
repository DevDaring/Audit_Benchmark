_TEX_ESCAPES = {"&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#",
                "_": r"\_", "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}",
                "^": r"\textasciicircum{}"}


def _tex(s: str) -> str:
    return "".join(_TEX_ESCAPES.get(c, c) for c in str(s))


def _disp(m: str) -> str:
    return DISPLAY.get(m, m)


def _prov(table: str, quantity: str, source: Path) -> None:
    PROVENANCE.append({
        "float": table,
        "quantity": quantity,
        "source_file": str(source.relative_to(RESULTS_DIR.parent)).replace("\\", "/"),
    })


def _float(label: str, caption: str, body: str, wide: bool = False,
           size: str = r"\small") -> str:
    """A booktabs table wrapped in adjustbox, caption above, as the house style requires."""
    env = "table*" if wide else "table"
    return (
        f"%% generated by TIST/make_tables.py -- do not edit by hand\n"
        f"\\begin{{{env}}}[t]\n"
        f"\\caption{{{caption}}}\n"
        f"\\label{{{label}}}\n"
        f"\\centering\n{size}\n"
        f"\\begin{{adjustbox}}{{max width=\\linewidth}}\n"
        f"{body}\n"
        f"\\end{{adjustbox}}\n"
        f"\\end{{{env}}}\n"
    )


# ---------------------------------------------------------------------------
# tab:cost -- wall clock reconstructed from the run logs
# ---------------------------------------------------------------------------
def table_cost(out: Path) -> None:
    """Per-model wall clock on the battery lease, read from the timestamps in the logs.

    Scope matters and is stated in the caption: this is the TIST battery lease, which
    covers the causal battery and the multilingual behavioural runs for the four open
    models. It is not the cost of the original English audit, which ran on an earlier
    lease whose logs record no timings.
    """
    ts = re.compile(r"^(\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2})")
    rows, total = [], 0.0
    for m in OPEN_ORDER:
        p = LOGDIR / f"run_{m}.log"
        if not p.exists():
            continue
        stamps = [
            datetime.strptime(g.group(1), "%Y-%m-%d %H:%M:%S")
            for line in p.read_text(encoding="utf-8", errors="replace").splitlines()
            if (g := ts.match(line))
        ]
        if len(stamps) < 2:
            continue
        hours = (max(stamps) - min(stamps)).total_seconds() / 3600.0
        total += hours
        rows.append({"model": _disp(m), "hours": hours})
        _prov("tab:cost", f"wall clock, {_disp(m)}", p)
    if not rows:
        log.warning("no run logs with timestamps; skipping tab:cost")
        return

    env = json.loads((TIST / "environment.json").read_text(encoding="utf-8"))
    _prov("tab:cost", "GPU, library versions", TIST / "environment.json")

    body = [r"\begin{tabular}{lr}", r"\toprule",
            r"Model & Wall clock (h) \\", r"\midrule"]
    body += [f"{r['model']} & {r['hours']:.2f} \\\\" for r in rows]
    body += [r"\midrule", f"Total & {total:.2f} \\\\", r"\bottomrule", r"\end{tabular}"]

    cap = (f"Wall clock per model for the causal battery and multilingual behavioural runs, "
           f"on one {env['gpu'].replace('NVIDIA ', '')}.")
    (out / "tab_cost.tex").write_text(_float("tab:cost", cap, "\n".join(body)),
                                      encoding="utf-8")


