# tab:repair -- how answers were extracted
# ---------------------------------------------------------------------------
def table_repair(out: Path) -> dict:
    """Where each parsed answer came from.

    The manuscript needs this because "a language model repairs malformed output" was an
    overstatement: the model-based route touched under two per cent of responses on one
    model and under one tenth of a per cent on another, while the heavy fallback is
    deterministic and concentrated on a single model.
    """
    src = RESULTS_DIR / "behavioral_results.parquet"
    df = pd.read_parquet(src, columns=["model_name", "parse_method"])
    _prov("tab:repair", "parse method distribution per model", src)

    tab = pd.crosstab(df["model_name"], df["parse_method"])
    pct = tab.div(tab.sum(axis=1), axis=0) * 100
    det = [c for c in ("json_repaired", "quoted_lines", "regex") if c in pct.columns]
    judge = [c for c in pct.columns if c.startswith("judge_")]

    order = [m for m in OPEN_ORDER + ["mistral-medium", "qwen3-next-80b-a3b",
                                      "amazon-nova-2-lite", "gemini-2.5-flash"]
             if m in pct.index]
    body = [r"\begin{tabular}{lrrrr}", r"\toprule",
            r"Model & Direct & Deterministic & Model-based & Unparsable \\",
            r" & (\%) & fallback (\%) & repair (\%) & (\%) \\", r"\midrule"]
    for m in order:
        body.append(
            f"{_disp(m)} & {pct.loc[m, 'json']:.2f} & {pct.loc[m, det].sum():.2f} & "
            f"{pct.loc[m, judge].sum() if judge else 0:.2f} & "
            f"{pct.loc[m, 'failed'] if 'failed' in pct.columns else 0:.2f} \\\\"
        )
    body += [r"\bottomrule", r"\end{tabular}"]

    cap = (f"Origin of every parsed answer across {len(df):,} behavioural responses. "
           r"Model-based repair is the only route that could introduce an answer.")
    (out / "tab_repair.tex").write_text(_float("tab:repair", cap, "\n".join(body)),
                                        encoding="utf-8")

    return {
        "n_responses": int(len(df)),
        "max_judge_pct": float(pct[judge].sum(axis=1).max()) if judge else 0.0,
        "max_judge_model": _disp(pct[judge].sum(axis=1).idxmax()) if judge else "--",
        "max_det_pct": float(pct[det].sum(axis=1).max()),
        "max_det_model": _disp(pct[det].sum(axis=1).idxmax()),
        "no_fallback": [_disp(m) for m in order
                        if pct.loc[m, det].sum() + (pct.loc[m, judge].sum() if judge else 0) == 0],
    }


