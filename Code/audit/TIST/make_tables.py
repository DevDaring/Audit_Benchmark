# tab:multi -- severity and validity gap, competent pairs only
# ---------------------------------------------------------------------------
def table_multi(out: Path) -> dict:
    sev_src = TIST / "e4" / "stats_e4_severity.csv"
    gap_src = TIST / "e4" / "stats_e4_validity_gap.csv"
    comp = json.loads((TIST / "e4" / "competence.json").read_text(encoding="utf-8"))
    sev = pd.read_csv(sev_src)
    gap = pd.read_csv(gap_src)
    _prov("tab:multi", "mean |C|, commutativity index", sev_src)
    _prov("tab:multi", "native and audit-robust pass, validity gap", gap_src)

    # The gate is applied here, not upstream: severity is computed before the verdict.
    ok = {(v["model_name"], v["lang"]) for v in comp.values() if v["competent"]}
    dropped = [(r["model_name"], r["lang"]) for _, r in sev.iterrows()
               if (r["model_name"], r["lang"]) not in ok]
    for m, lg in dropped:
        log.info("dropping %s / %s from tab:multi: gated out on competence", m, lg)
    sev = sev[[(r.model_name, r.lang) in ok for r in sev.itertuples()]]

    merged = sev.merge(gap, on=["lang", "model_name"], how="left", suffixes=("", "_g"))
    body = [r"\begin{tabular}{llrrrrr}", r"\toprule",
            r"Language & Model & Seeds & Mean $|C|$ & Commut. & Native & Gap \\",
            r"\midrule"]
    for lg in ("hi", "bn"):
        sub = merged[merged["lang"] == lg].sort_values("severity_mean_absC")
        for i, (_, r) in enumerate(sub.iterrows()):
            name = LANG[lg] if i == 0 else ""
            nat = "--" if pd.isna(r.get("native_pass")) else f"{r['native_pass']:.3f}"
            g = ("--" if pd.isna(r.get("validity_gap"))
                 else f"{r['validity_gap']:.3f} [{r['gap_ci_lo']:.3f}, "
                      f"{r['gap_ci_hi']:.3f}]")
            body.append(
                f"{name} & {_disp(r['model_name'])} & {int(r['n_seeds'])} & "
                f"{r['severity_mean_absC']:.3f} & {r['commutativity_index']:.3f} & "
                f"{nat} & {g} \\\\"
            )
        body.append(r"\addlinespace")
    body = body[:-1] + [r"\bottomrule", r"\end{tabular}"]

    cap = ("Multilingual audit over the pairs the competence gate admits. Gap is native "
           "minus audit-robust pass, with a bootstrap interval.")
    (out / "tab_multi.tex").write_text(_float("tab:multi", cap, "\n".join(body), wide=True),
                                       encoding="utf-8")

    zero = gap[gap["validity_gap"] <= 0]
    return {
        "n_reported": int(len(sev)),
        "n_dropped": len(dropped),
        "zero_gap_pairs": [f"{_disp(r['model_name'])}/{LANG[r['lang']]}"
                           for _, r in zero.iterrows()],
    }


